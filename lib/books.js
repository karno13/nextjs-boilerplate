export const BOOKS = [];
let section = "";
let id = 1;

for (const line of RAW.split("\n")) {
  if (!line) continue;

  if (line.startsWith("#")) {
    section = line.slice(1);
    continue;
  }

  const [
    originalTitle,
    polishTitle = "",
    note = "",
    confirm = ""
  ] = line.split("|");

  BOOKS.push({
    id: id++,
    section,
    originalTitle,
    polishTitle: polishTitle || null,
    note: note || null,
    needsConfirmation: confirm === "1",
    searchTerms: [
      polishTitle,
      originalTitle
    ].filter(Boolean),
  });
}

export default BOOKS;
